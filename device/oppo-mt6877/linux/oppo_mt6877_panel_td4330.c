/*
 * OPPO MT6877 panel: TD4330 FHD+ DSI command-mode (AUO glass).
 *
 * WHAT IT IS. A drm_panel driver for the 1080x2280 command-mode panel on
 * 20181-class boards. The init sequence below is init_setting_cmd[] from the
 * vendor LCM driver, transcribed entry for entry -- including the two vendor
 * quirks that must survive the transcription:
 *
 *   - C2 claims 0x78 bytes but lists 67; the vendor struct zero-pads the
 *     rest, so 53 zero bytes really go on the wire. This driver keeps the
 *     vendor's para_list[200] shape precisely so the padding is automatic.
 *   - D2 claims 3 bytes but lists 4; the vendor sends 3. Same shape, same
 *     behaviour, no special case.
 *   - Display-on (0x29) is sent BEFORE sleep-out (0x11). Unusual, but it is
 *     what the stock boot does, and the panel lights with it.
 *
 * THE HANDOFF RULE (from the J36 panel driver): Linux adopts the bootloader's
 * panel rather than re-initialising it. enable() sends the init table only
 * when the panel is not already on -- tracked by a prepared flag, since DCS
 * reads are not wired -- so a driver reload does not blank the glass.
 *
 * From: drivers/misc/mediatek/lcm/td4330_fhdp_dsi_cmd_auo_rt5081/
 *       td4330_fhdp_dsi_cmd_auo_rt5081.c
 */

